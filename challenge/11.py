colors=['red','green','blue']#membuat list berisi red green blue
print(colors[0])#mencetak warna pertama dari list yaitu red
colors[1]='yellow'#mengubah warna kedua menjadi yellow
print(colors[1])#mencetak warna kedua dari list yaitu yellow
colors.append('purple')#menambahkan warna purple ke list
print(colors)#mencetak semua warna dalam list
colors.remove('red')#menghapus warna red dari list   
print(colors)#mengencetak semua warna dalam list setelah red dihapus

